  restoreRequested,
  trialIdentityStarted,
  trialIdentityFailed,
  trialIdTokenMissing,
  trialIdTokenReady,
  trialDeviceReady,
  trialInputInvalid,
  trialIntegrityStarted,
  trialIntegrityReady,
  trialIntegrityFailed,
  trialWorkerRequest,
  trialWorkerHttpFailed,
  trialWorkerResponseInvalid,
  trialWorkerFailed,
  trialWorkerActive,
  trialWorkerExpired,
  trialWorkerBlocked,
  trialWorkerUnavailable,
  trialGrantRejected,
  trialGrantAccepted,
  trialControllerFailed,
}

void entitlementTrace(EntitlementEvent event) {
  // Enum-only logging prevents accidental interpolation of sensitive data.
  if (entitlementDiagnosticsEnabled) {
    debugPrint('YP_ENTITLEMENT ${event.name}');
  }
}
